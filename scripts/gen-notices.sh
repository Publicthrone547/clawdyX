#!/bin/sh
# Regenerates THIRD_PARTY_NOTICES.md from the Go modules linked into the
# shipped binaries (macOS, Windows and Linux) (and, when present, the desktop frontend's production
# npm dependencies). Run from the repository root: scripts/gen-notices.sh
set -eu
out=THIRD_PARTY_NOTICES.md
{
  echo "# Third-party notices"
  echo
  echo "clawdyX itself is licensed under the PolyForm Noncommercial License 1.0.0 (see LICENSE)."
  echo "That license does not apply to the components below; each keeps its own license, reproduced here"
  echo "as required for binary redistribution. Generated by scripts/gen-notices.sh — do not edit by hand."
  echo
  echo "## Go modules linked into the binaries"
  echo
  echo "| Module | Version | License file |"
  echo "| --- | --- | --- |"
  fmt='{{if and (not .Standard) .Module}}{{if not .Module.Main}}{{if not (eq .Module.Path "github.com/Publicthrone547/clawdyX")}}{{.Module.Path}} {{.Module.Version}} {{.Module.Dir}}{{end}}{{end}}{{end}}'
  {
    for os in darwin windows linux; do
      GOOS=$os GOARCH=amd64 CGO_ENABLED=0 go list -deps -f "$fmt" ./cmd/clawdyx ./cmd/clawdyxw
    done
    if [ -f desktop/go.mod ]; then
      (cd desktop && GOOS=darwin GOARCH=arm64 CGO_ENABLED=1 go list -deps -tags production -f "$fmt" .)
      (cd desktop && GOOS=linux GOARCH=amd64 CGO_ENABLED=1 go list -deps -tags production,gtk3 -f "$fmt" .)
      (cd desktop && GOOS=windows GOARCH=amd64 CGO_ENABLED=0 go list -deps -tags production -f "$fmt" .)
    fi
  } | sort -u > /tmp/clawdyx-mods.$$
  while read -r p v d; do
    lic=$(ls "$d" | grep -i -m1 -E '^(license|licence|copying)' || true)
    echo "| \`$p\` | $v | ${lic:-not found} |"
  done < /tmp/clawdyx-mods.$$
  echo
  while read -r p v d; do
    lic=$(ls "$d" | grep -i -m1 -E '^(license|licence|copying)' || true)
    [ -n "$lic" ] || continue
    echo "### $p $v"
    echo
    echo '```text'
    cat "$d/$lic"
    echo '```'
    echo
  done < /tmp/clawdyx-mods.$$
  rm -f /tmp/clawdyx-mods.$$
  if [ -f desktop/frontend/package.json ] && [ -d desktop/frontend/node_modules ]; then
    echo "## Frontend packages bundled into the desktop app"
    echo
    (cd desktop/frontend && node -e '
      const fs=require("fs"),path=require("path");
      const pkg=JSON.parse(fs.readFileSync("package.json"));
      const seen=new Set(); const rows=[];
      function walk(name){ if(seen.has(name)) return; seen.add(name);
        const dir=path.join("node_modules",name); let p;
        try{p=JSON.parse(fs.readFileSync(path.join(dir,"package.json")));}catch{return}
        const lf=fs.readdirSync(dir).find(f=>/^(license|licence)/i.test(f));
        rows.push({name,version:p.version,license:p.license||"?",text:lf?fs.readFileSync(path.join(dir,lf),"utf8"):""});
        for(const d of Object.keys(p.dependencies||{})) walk(d);
      }
      for(const d of [...Object.keys(pkg.dependencies||{}), "tailwindcss"]) walk(d); // the Tailwind-generated CSS is bundled
      rows.sort((a,b)=>a.name.localeCompare(b.name));
      console.log("| Package | Version | License |\n| --- | --- | --- |");
      for(const r of rows) console.log(`| \`${r.name}\` | ${r.version} | ${r.license} |`);
      console.log();
      for(const r of rows) if(r.text) console.log(`### ${r.name} ${r.version}\n\n\`\`\`text\n${r.text.trim()}\n\`\`\`\n`);
    ')
  fi
} > "$out"
echo "wrote $out"
